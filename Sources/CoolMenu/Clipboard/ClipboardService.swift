import AppKit
import Combine
import CoolMenuCore

/// Records pasteboard changes into a local history. Never synced: the history can hold anything
/// the user copies, so it stays in Application Support on this Mac.
final class ClipboardService: ObservableObject {
    static let shared = ClipboardService()

    @Published private(set) var history = ClipHistory()

    /// Markers apps set on secrets and throwaway content (nspasteboard.org conventions).
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private let store = SettingsStore.shared
    private let historyURL = AppPaths.support.appendingPathComponent("history.json")
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var saveCancellable: AnyCancellable?
    private var cancellables: Set<AnyCancellable> = []
    private let imageCache = NSCache<NSString, NSImage>()
    /// Apps that were frontmost until recently. The poll can run after the user has already
    /// switched away from the app that copied, so exclusions check these too.
    private var frontmostBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
    private var recentlyDeactivated: [(bundleID: String, at: Date)] = []

    private var settings: AppSettings { store.settings }

    func start() {
        if let data = try? Data(contentsOf: historyURL), let decoded = try? JSONDecoder().decode(ClipHistory.self, from: data) {
            history = decoded
        }
        saveCancellable = $history
            .dropFirst()
            .debounce(for: .seconds(1), scheduler: DispatchQueue.main)
            .sink { [weak self] _ in self?.flush() }

        NSWorkspace.shared.notificationCenter
            .publisher(for: NSWorkspace.didActivateApplicationNotification)
            .sink { [weak self] note in
                guard let self else { return }
                let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
                if let previous = frontmostBundleID { recentlyDeactivated.append((previous, Date())) }
                frontmostBundleID = app?.bundleIdentifier
            }
            .store(in: &cancellables)

        store.observe(\.clipboardLimit)
            .sink { [weak self] limit in
                self?.mutate { $0.trim(limit: limit) }
            }
            .store(in: &cancellables)

        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard settings.clipboardEnabled else { return }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        if settings.clipboardIgnoreConcealed && !types.isDisjoint(with: Self.skippedTypes) { return }

        let source = NSWorkspace.shared.frontmostApplication
        recentlyDeactivated.removeAll { $0.at < Date().addingTimeInterval(-2) }
        let candidates = [source?.bundleIdentifier].compactMap { $0 } + recentlyDeactivated.map(\.bundleID)
        if candidates.contains(where: settings.clipboardExcludedBundleIDs.contains) { return }
        guard var item = capture(pasteboard) else { return }
        item.appBundleID = source?.bundleIdentifier
        item.appName = source?.localizedName
        if AX.isTrusted, let window = AX.focusedWindow() {
            item.windowTitle = AX.string(window, kAXTitleAttribute)
        }

        let limit = settings.clipboardLimit
        mutate { $0.insert(item, limit: limit) }
    }

    private func capture(_ pasteboard: NSPasteboard) -> ClipItem? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path)
            return ClipItem(kind: .files, filePaths: paths, contentHash: StableHash.of(paths.joined(separator: "\n")))
        }
        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let hash = StableHash.of(text)
            var rtfName: String?
            if let rtf = pasteboard.data(forType: .rtf) {
                let name = "\(hash).rtf"
                try? rtf.write(to: AppPaths.clips.appendingPathComponent(name))
                rtfName = name
            }
            return ClipItem(kind: .text, text: text, richTextFile: rtfName, contentHash: hash)
        }
        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
           let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) {
            let hash = StableHash.fnv1a(png)
            let name = "\(hash).png"
            try? png.write(to: AppPaths.clips.appendingPathComponent(name))
            return ClipItem(kind: .image, imageFile: name, contentHash: hash)
        }
        return nil
    }

    // MARK: Actions

    /// Puts `item` back on the pasteboard without recording it again.
    func copy(_ item: ClipItem, plainText: Bool = false) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text:
            if !plainText, let name = item.richTextFile, let rtf = try? Data(contentsOf: AppPaths.clips.appendingPathComponent(name)) {
                pasteboard.setData(rtf, forType: .rtf)
            }
            pasteboard.setString(item.text ?? "", forType: .string)
        case .files:
            let urls = (item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            if plainText {
                pasteboard.setString((item.filePaths ?? []).joined(separator: "\n"), forType: .string)
            } else {
                pasteboard.writeObjects(urls)
            }
        case .image:
            if let image = image(for: item) { pasteboard.writeObjects([image]) }
        }
        lastChangeCount = pasteboard.changeCount
        var moved = item
        moved.date = Date()
        let limit = settings.clipboardLimit
        mutate { $0.insert(moved, limit: limit) }
    }

    /// Copies, then sends ⌘V to the frontmost app once the panel has closed.
    func paste(_ item: ClipItem, plainText: Bool = false) {
        copy(item, plainText: plainText)
        guard AX.ensureTrusted(for: "pasting from history") else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.08) { KeySynth.paste() }
    }

    func togglePin(_ item: ClipItem) {
        mutate { h in
            h.togglePin(id: item.id)
            return []
        }
    }

    func delete(_ item: ClipItem) {
        mutate { h in h.remove(id: item.id).map { [$0] } ?? [] }
    }

    func clearUnpinned() {
        mutate { $0.clearUnpinned() }
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        if let cached = imageCache.object(forKey: name as NSString) { return cached }
        guard let image = NSImage(contentsOf: AppPaths.clips.appendingPathComponent(name)) else { return nil }
        imageCache.setObject(image, forKey: name as NSString)
        return image
    }

    /// Writes the history now. Called by the debounced save and on quit.
    func flush() {
        try? JSONEncoder().encode(history).write(to: historyURL, options: .atomic)
    }

    /// Applies a change and removes side files that no remaining item references.
    private func mutate(_ change: (inout ClipHistory) -> [ClipItem]) {
        var h = history
        let removed = change(&h)
        history = h
        let stillUsed = Set(h.items.flatMap(\.storedFiles))
        for name in removed.flatMap(\.storedFiles) where !stillUsed.contains(name) {
            try? FileManager.default.removeItem(at: AppPaths.clips.appendingPathComponent(name))
        }
    }
}
